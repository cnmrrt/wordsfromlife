          <strong>Anlamı:</strong> “Sekiz” anlamına gelen Latince
          <em>octo</em> sözcüğünden gelir.
        </p>
        <p>
          <strong>Kökeni:</strong> Roma takvimi on iki aylık bir sisteme
          dönüştürülmeden önce ekim, yılın sekizinci ayıydı.
        </p>
      </section>

      <section>
        <h2>11. Kasım (November)</h2>
        <p>
          <strong>Anlamı:</strong> “Dokuz” anlamına gelen Latince
          <em>novem</em> sözcüğünden gelir.
        </p>
        <p>
          <strong>Kökeni:</strong> Antik Roma'nın on aylık takviminde yılın
          dokuzuncu ayıydı.
        </p>
      </section>

