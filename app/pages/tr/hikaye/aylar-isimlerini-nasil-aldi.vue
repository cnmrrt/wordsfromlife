          <strong>Kökeni:</strong> Adın, Kuzey Yarımküre'de ilkbahar başlarken
          ağaçların, çiçeklerin ve bitkilerin açmasını ya da filizlenmesini
          anlattığı düşünülür. Bazı Antik Roma kaynakları ayı aşk tanrıçası
